/**
 * Toda la paleta se expone como variables CSS (`--<familia>-<tono>` en formato
 * "r g b") para poder alternar entre el tema oscuro "Dungeon" y el tema claro
 * "Pergamino" sin duplicar clases. Los valores por defecto son los hexadecimales
 * de Tailwind, de modo que el modo oscuro no cambia ni un píxel.
 *
 * El marcador `<alpha-value>` permite que Tailwind siga generando los
 * modificadores de opacidad (p. ej. `bg-amber-500/10`).
 */
const hexToRgb = (hex: string): string => {
  const value = hex.replace("#", "");
  const full =
    value.length === 3
      ? value
          .split("")
          .map((c) => c + c)
          .join("")
      : value;
  const int = parseInt(full, 16);
  return `${(int >> 16) & 255} ${(int >> 8) & 255} ${int & 255}`;
};

const scale = (family: string, shades: Record<string, string>): Record<string, string> =>
  Object.fromEntries(
    Object.entries(shades).map(([tone, hex]) => [
      tone,
      `rgb(var(--${family}-${tone}, ${hexToRgb(hex)}) / <alpha-value>)`,
    ])
  );

